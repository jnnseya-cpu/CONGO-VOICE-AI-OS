/**
 * Renders docs/DATA_RESIDENCY.md from the declarations in
 * src/server/core/residency.ts, so the written inventory and the code that
 * enforces it cannot say different things.
 *
 *   npm run residency:doc
 *
 * tests/residency.test.ts fails if the file is out of date.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The destinations are read from the TypeScript source rather than imported:
 * the module is server-only and reads the environment, and this document
 * describes what the platform *can* reach, not what one machine happens to
 * have configured.
 */
const source = fs.readFileSync(path.join(ROOT, "src/server/core/residency.ts"), "utf8");
const block = source.slice(source.indexOf("export const DESTINATIONS"), source.indexOf("\n];", source.indexOf("export const DESTINATIONS")));

const entries = [...block.matchAll(/\{\s*id:\s*"([^"]+)",\s*kind:\s*"([^"]+)",\s*sends:\s*"((?:[^"\\]|\\.)*)",\s*operator:\s*"((?:[^"\\]|\\.)*)",\s*jurisdictions:\s*\(\)\s*=>\s*([\s\S]*?),\s*onSafetyPath:\s*(true|false),\s*ifRefused:\s*"((?:[^"\\]|\\.)*)",/g)].map((m) => ({
  id: m[1],
  kind: m[2],
  sends: m[3].replace(/\\"/g, '"'),
  operator: m[4].replace(/\\"/g, '"'),
  jurisdictions: m[5].trim(),
  onSafetyPath: m[6] === "true",
  ifRefused: m[7].replace(/\\"/g, '"'),
}));

/* Every declared id must have been parsed. A destination that slipped past the
 * parser would be missing from the inventory while still being reachable at
 * runtime, which is the one failure this document must not have. */
const declaredIds = [...block.matchAll(/^\s{4}id:\s*"([^"]+)"/gm)].map((m) => m[1]);
const parsedIds = entries.map((e) => e.id);
const missed = declaredIds.filter((id) => !parsedIds.includes(id));
if (entries.length === 0 || missed.length > 0) {
  console.error(`Declaration shape in residency.ts changed; not parsed: ${missed.join(", ") || "all"}`);
  process.exit(1);
}

const KIND = {
  self: "The deployment itself",
  ai_provider: "AI provider",
  channel: "Communication channel",
  infrastructure: "Infrastructure",
};

function jurisdictionLabel(expr) {
  if (expr.startsWith("[") && expr.endsWith("]")) {
    const inner = expr.slice(1, -1).trim();
    if (inner.startsWith('"')) return inner.replace(/"/g, "");
    if (inner.includes("deploymentJurisdiction")) return "same as the deployment (`DEPLOYMENT_JURISDICTION`)";
    const override = inner.match(/process\.env\.([A-Z_]+)[\s\S]*\|\|\s*"([A-Z]{2})"/);
    if (override) return `${override[2]} (override with \`${override[1]}\`)`;
    return inner;
  }
  if (expr.includes("selfHostedSpeechJurisdictions")) return "US, or the declared location of a self-hosted endpoint (`AI_SELF_HOSTED_JURISDICTION`)";
  return expr;
}

const lines = [];
lines.push("# Where citizen data can go");
lines.push("");
lines.push("<!-- Generated by scripts/build-residency-doc.mjs from the declarations in");
lines.push("     src/server/core/residency.ts. Do not edit by hand: tests/residency.test.ts");
lines.push("     fails if this file and the code disagree. -->");
lines.push("");
lines.push("Every destination a citizen's words, voice, photographs or telephone number");
lines.push("can reach, and what each one receives. This is the inventory a legal review");
lines.push("asks for, and it is generated from the same declarations the platform enforces");
lines.push("at runtime — so it cannot describe a system other than the one that is running.");
lines.push("");
lines.push("## The position");
lines.push("");
lines.push("The programme's intent is that everything stays in the Democratic Republic of");
lines.push("the Congo. There is no cloud region in the country, so the pilot runs from the");
lines.push("nearest available one and migrates when an in-country option exists. That is a");
lines.push("decision with a date on it, not a permanent posture, and this document exists so");
lines.push("that the gap between the intent and the deployment is stated rather than assumed.");
lines.push("");
lines.push("## How it is enforced");
lines.push("");
lines.push("`DATA_RESIDENCY` names the jurisdictions a deployment permits, as a comma-separated");
lines.push("list of ISO 3166-1 alpha-2 codes. A destination outside that set is **never");
lines.push("registered**: it has no code path, so no ordering, retry or fallback can reach it.");
lines.push("A message channel outside it returns a delivery failure, which the escalation path");
lines.push("reports and the readiness probe degrades on — the argument for changing the policy");
lines.push("or the carrier, made at the moment it matters rather than after an incident.");
lines.push("");
lines.push("Unset means unrestricted. That is right on a laptop and is reported as a finding");
lines.push("in any deployment that serves citizens.");
lines.push("");
lines.push("## What moving the container does not fix");
lines.push("");
lines.push("A voice recording sent to a transcription service abroad has left the country");
lines.push("whether the server is in Johannesburg or in Kinshasa. The providers below are the");
lines.push("residency question; the hosting is the smaller half of it.");
lines.push("");
lines.push("## The inventory");
lines.push("");
lines.push("| Destination | Kind | Operator | Jurisdiction | On the safety path | What it receives |");
lines.push("|---|---|---|---|---|---|");
for (const e of entries) {
  lines.push(`| \`${e.id}\` | ${KIND[e.kind] ?? e.kind} | ${e.operator} | ${jurisdictionLabel(e.jurisdictions)} | ${e.onSafetyPath ? "yes" : "no"} | ${e.sends} |`);
}
lines.push("");
lines.push("## What is lost if a destination is refused");
lines.push("");
for (const e of entries) {
  lines.push(`- **\`${e.id}\`** — ${e.ifRefused}`);
}
lines.push("");
lines.push("## The strictest useful setting");
lines.push("");
lines.push("```");
lines.push("DATA_RESIDENCY=CD");
lines.push("DEPLOYMENT_JURISDICTION=CD");
lines.push("```");
lines.push("");
lines.push("Every remote provider is refused. The platform still triages by protocol, still");
lines.push("detects danger signs, still grades severity and still speaks the fixed emergency");
lines.push("scripts — none of that ever used a model. What it loses is understanding free");
lines.push("speech and transcribing a voice note. That is a different product, and under a");
lines.push("strict localisation requirement it is the honest one.");
lines.push("");

const out = path.join(ROOT, "docs/DATA_RESIDENCY.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`${entries.length} destinations written to ${path.relative(ROOT, out)}`);
